#!/usr/bin/env node
/**
 * generate-llms-txt.js — Generate a root `llms.txt` index of this repo.
 *
 * Implements the llms.txt convention (https://llmstxt.org/): a curated,
 * machine-readable index of the project's most useful documents and components,
 * so that LLM-based tools can quickly discover what this plugin offers.
 *
 * Run directly to (re)write `llms.txt`. Import `generate()` to obtain the
 * content as a string (used by scripts/ci/validate-llms-txt.js to detect drift).
 */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT_DIR = path.resolve(__dirname, '..');

/** Minimal YAML frontmatter field reader (single-line `key: value`). */
function readFrontmatterField(content, field) {
  const fmMatch = content.match(/^\uFEFF?---\r?\n([\s\S]*?)\r?\n---/);
  if (!fmMatch) return null;
  const line = fmMatch[1].split(/\r?\n/).find((l) => l.trim().startsWith(`${field}:`));
  if (!line) return null;
  return line
    .slice(line.indexOf(':') + 1)
    .trim()
    .replace(/^["']|["']$/g, '');
}

function firstSentence(text, max = 160) {
  if (!text) return '';
  const flat = text.replace(/\s+/g, ' ').trim();
  const end = flat.search(/(?<=\.)\s/);
  const sentence = end > 0 ? flat.slice(0, end) : flat;
  return sentence.length > max ? `${sentence.slice(0, max - 1)}…` : sentence;
}

function listMarkdown(dir) {
  const abs = path.join(ROOT_DIR, dir);
  if (!fs.existsSync(abs)) return [];
  return fs
    .readdirSync(abs)
    .filter((f) => f.endsWith('.md'))
    .sort();
}

function agentEntries() {
  return listMarkdown('agents').map((file) => {
    const content = fs.readFileSync(path.join(ROOT_DIR, 'agents', file), 'utf8');
    const name = readFrontmatterField(content, 'name') || file.replace(/\.md$/, '');
    const desc = firstSentence(readFrontmatterField(content, 'description') || '');
    return `- [${name}](agents/${file})${desc ? `: ${desc}` : ''}`;
  });
}

function skillEntries() {
  const abs = path.join(ROOT_DIR, 'skills');
  if (!fs.existsSync(abs)) return [];
  return fs
    .readdirSync(abs, { withFileTypes: true })
    .filter((d) => d.isDirectory() && fs.existsSync(path.join(abs, d.name, 'SKILL.md')))
    .map((d) => d.name)
    .sort()
    .map((dirName) => {
      const content = fs.readFileSync(path.join(abs, dirName, 'SKILL.md'), 'utf8');
      const name = readFrontmatterField(content, 'name') || dirName;
      const desc = firstSentence(readFrontmatterField(content, 'description') || '');
      return `- [${name}](skills/${dirName}/SKILL.md)${desc ? `: ${desc}` : ''}`;
    });
}

function commandEntries() {
  return listMarkdown('commands').map((file) => {
    const content = fs.readFileSync(path.join(ROOT_DIR, 'commands', file), 'utf8');
    const desc = firstSentence(readFrontmatterField(content, 'description') || '');
    const name = `/${file.replace(/\.md$/, '')}`;
    return `- [${name}](commands/${file})${desc ? `: ${desc}` : ''}`;
  });
}

function generate() {
  const lines = [];
  lines.push('# Everything Claude Code');
  lines.push('');
  lines.push(
    '> A comprehensive, battle-tested collection of Claude Code configurations: ' +
      'agents, skills, commands, rules, hooks, and MCP server configs. Works across ' +
      'Claude Code, Codex, Cursor, and OpenCode.'
  );
  lines.push('');
  lines.push(
    'This file is auto-generated by `scripts/generate-llms-txt.js`. Do not edit by hand; ' +
      'run `npm run llms` to regenerate.'
  );
  lines.push('');

  lines.push('## Documentation');
  const docs = [
    ['README.md', 'Project overview, installation, and feature catalog'],
    ['CONTRIBUTING.md', 'How to contribute agents, skills, hooks, and commands'],
    ['the-shortform-guide.md', 'Setup, foundations, and philosophy — read first'],
    ['the-longform-guide.md', 'Token optimization, memory persistence, evals, parallelization'],
    ['the-security-guide.md', 'Security best practices for AI agent harnesses'],
    ['the-openclaw-guide.md', 'OpenCode-specific workflows'],
  ];
  for (const [file, desc] of docs) {
    if (fs.existsSync(path.join(ROOT_DIR, file))) lines.push(`- [${file}](${file}): ${desc}`);
  }
  lines.push('');

  const agents = agentEntries();
  lines.push(`## Agents (${agents.length})`);
  lines.push(...agents);
  lines.push('');

  const skills = skillEntries();
  lines.push(`## Skills (${skills.length})`);
  lines.push(...skills);
  lines.push('');

  const commands = commandEntries();
  lines.push(`## Commands (${commands.length})`);
  lines.push(...commands);
  lines.push('');

  lines.push('## Optional');
  lines.push('- [Rules](rules/): Layered, language-specific coding rules (common + per-language)');
  lines.push('- [Hooks](hooks/README.md): Trigger-based automations for the Claude Code lifecycle');
  lines.push(
    '- [MCP configs](mcp-configs/mcp-servers.json): Ready-to-use MCP server configurations'
  );
  lines.push('');

  return lines.join('\n');
}

const OUTPUT_PATH = path.join(ROOT_DIR, 'llms.txt');

if (require.main === module) {
  fs.writeFileSync(OUTPUT_PATH, generate(), 'utf8');
  process.stdout.write(`Wrote ${OUTPUT_PATH}\n`);
}

module.exports = { generate, OUTPUT_PATH };
